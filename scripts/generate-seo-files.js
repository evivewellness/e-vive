/**
 * Writes public/robots.txt and public/sitemap.xml.
 *
 * Both need the canonical origin, and hardcoding it in two static files is a
 * trap the first time the domain changes. This runs as `prebuild`, so the files
 * always match NEXT_PUBLIC_SITE_URL for the deployment being built.
 *
 * Only genuinely public pages are listed. Portals, admin, and anything reached
 * by a token are excluded from the sitemap and disallowed in robots.txt — a
 * reset link or a shared care summary appearing in a search index would be a
 * disclosure, and `/admin` already carries a noindex meta tag but should not
 * have been crawled to discover that.
 */

const fs = require('fs');
const path = require('path');

const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || 'https://e-vive.vercel.app').replace(/\/$/, '');

// path → how often it changes → how much it matters, relatively.
const PUBLIC_PAGES = [
  { path: '/',            changefreq: 'weekly',  priority: '1.0' },
  { path: '/match/',      changefreq: 'daily',   priority: '0.9' },
  { path: '/assistants/', changefreq: 'monthly', priority: '0.8' },
  { path: '/caregivers/', changefreq: 'weekly',  priority: '0.8' },
  { path: '/about/',      changefreq: 'monthly', priority: '0.7' },
  { path: '/partners/',   changefreq: 'monthly', priority: '0.7' },
  { path: '/contact/',    changefreq: 'monthly', priority: '0.6' },
  { path: '/products/',   changefreq: 'monthly', priority: '0.5' },
  { path: '/privacy/',    changefreq: 'yearly',  priority: '0.3' },
  { path: '/terms/',      changefreq: 'yearly',  priority: '0.3' },
  { path: '/accessibility/', changefreq: 'yearly', priority: '0.3' },
  { path: '/hca/apply/',  changefreq: 'monthly', priority: '0.8' },
];

// Nothing behind a sign-in or a token should be crawled.
const DISALLOWED = [
  '/admin/',
  '/client/',
  '/hca/',
  '/report/',
  '/auth/',
  '/api/',
];

// Carved back out of the blanket /hca/ rule: the application form is a public
// recruitment page and should be findable. Crawlers resolve the most specific
// matching rule, so this wins over the Disallow above.
const ALLOWED = ['/hca/apply'];

function robotsTxt() {
  return [
    '# E-Vive Kenya',
    '# Generated by scripts/generate-seo-files.js — edit that, not this.',
    '',
    'User-agent: *',
    ...DISALLOWED.map(p => `Disallow: ${p}`),
    ...ALLOWED.map(p => `Allow: ${p}`),
    'Allow: /',
    '',
    `Sitemap: ${SITE_URL}/sitemap.xml`,
    '',
  ].join('\n');
}

function sitemapXml(lastmod) {
  const urls = PUBLIC_PAGES.map(page => [
    '  <url>',
    `    <loc>${SITE_URL}${page.path}</loc>`,
    `    <lastmod>${lastmod}</lastmod>`,
    `    <changefreq>${page.changefreq}</changefreq>`,
    `    <priority>${page.priority}</priority>`,
    '  </url>',
  ].join('\n')).join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    urls,
    '</urlset>',
    '',
  ].join('\n');
}

const publicDir = path.join(__dirname, '..', 'public');
const lastmod = new Date().toISOString().slice(0, 10);

fs.writeFileSync(path.join(publicDir, 'robots.txt'), robotsTxt());
fs.writeFileSync(path.join(publicDir, 'sitemap.xml'), sitemapXml(lastmod));

console.log(`[seo] wrote robots.txt and sitemap.xml for ${SITE_URL} (${PUBLIC_PAGES.length} pages)`);
